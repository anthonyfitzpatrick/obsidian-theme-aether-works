// Builds the distributable theme.css: the embedded typewriter face, the option classes and
// the optional Style Settings block, then src/*.css in filename order. It also writes
// snippets/: one CSS snippet per option, and the optional "Period typefaces" snippet that
// carries the larger embedded faces. --check fails if any output is stale, so CI and the
// pre-commit hook catch hand edits.
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { EMBEDDED_FACES, type EmbeddedFace, LATIN_RANGE, LICENCE_TEXTS, PERIOD_SNIPPET_TITLE, PERIOD_STACKS } from "./fonts.ts";
import { optionRules, SNIPPET_PREFIX, snippetCss, snippetFileName, styleSettingsBlock, THEME_OPTIONS } from "./options.ts";
import { projectRoot } from "./project.ts";

const sourceDir = join(projectRoot, "src");
const fontDir = join(projectRoot, "fonts");
const outputPath = join(projectRoot, "theme.css");
const snippetDir = join(projectRoot, "snippets");

function fontFaceRule(face: EmbeddedFace): string {
  const data = readFileSync(join(fontDir, face.file)).toString("base64");
  return [
    "@font-face {",
    `  font-family: "${face.family}";`,
    `  font-style: ${face.style};`,
    `  font-weight: ${face.weight};`,
    "  font-display: swap;",
    `  src: url("data:font/woff2;base64,${data}") format("woff2");`,
    `  unicode-range: ${LATIN_RANGE};`,
    "}",
  ].join("\n");
}

const modules = readdirSync(sourceDir)
  .filter((file) => file.endsWith(".css"))
  .sort();
const banner = "/* Aether Works for Obsidian. Generated from src/ and fonts/ by scripts/build.ts. Do not edit directly. */\n\n";
// The OFL requires each copy of the fonts to carry their copyright notices and the licence.
// Obsidian installs only theme.css and manifest.json, and a snippet travels on its own, so
// each file that embeds a face carries the full text.
function embeddedFonts(faces: readonly EmbeddedFace[]): string {
  const credits = [...new Set(faces.map((face) => `${face.designFamily} (${face.licence})`))];
  const licences = [...new Set(faces.map((face) => LICENCE_TEXTS[face.licence]))].map((path) =>
    readFileSync(join(projectRoot, path), "utf8").trim().replaceAll("*/", "* /"),
  );
  return `/* Embedded typefaces, Latin subsets: ${credits.join("; ")}.\n\n${licences.join("\n\n")}\n*/\n${faces.map(fontFaceRule).join("\n")}\n`;
}

const themeFaces = EMBEDDED_FACES.filter((face) => face.bundle === "theme");
const snippetFaces = EMBEDDED_FACES.filter((face) => face.bundle === "snippet");
const fonts = `${embeddedFonts(themeFaces)}\n`;

const periodSnippet =
  `/* Aether Works: ${PERIOD_SNIPPET_TITLE}.\n` +
  "   Embeds Playfair Display, IM Fell English and Cinzel, the typefaces the theme was designed\n" +
  "   with, in place of the period-style serifs your system provides. Turn it on or off under\n" +
  "   Settings → Appearance → CSS snippets. No plugin needed. It is about 250 KB, which is why\n" +
  "   it isn't part of theme.css. Generated by scripts/build.ts; edit that, not this file. */\n" +
  embeddedFonts(snippetFaces) +
  `body {\n${PERIOD_STACKS.map((stack) => `  ${stack.property}: ${stack.value};`).join("\n")}\n}\n`;
const options =
  "/* Options: the variables the theme reads, with their defaults. The classes below apply an\n" +
  "   option to a note (its cssclasses property) or, through the optional Style Settings\n" +
  "   plugin, to the vault. The CSS snippets in snippets/ do it vault-wide with no plugin. */\n" +
  optionRules() +
  "\n\n" +
  styleSettingsBlock() +
  "\n\n";
const css = banner + fonts + options + modules.map((file) => `${readFileSync(join(sourceDir, file), "utf8").trimEnd()}\n`).join("\n");

const snippets = new Map([
  ...THEME_OPTIONS.map((option): [string, string] => [snippetFileName(option), snippetCss(option)]),
  [`${SNIPPET_PREFIX}${PERIOD_SNIPPET_TITLE}.css`, periodSnippet],
]);

function isCurrent(path: string, text: string): boolean {
  return existsSync(path) && readFileSync(path, "utf8") === text;
}

/** Every generated file that differs from what the build would write, and any leftovers. */
function staleOutputs(): readonly string[] {
  const present = existsSync(snippetDir) ? readdirSync(snippetDir) : [];
  const stale = present.filter((file) => !snippets.has(file)).map((file) => `snippets/${file}`);
  for (const [file, text] of snippets) if (!isCurrent(join(snippetDir, file), text)) stale.push(`snippets/${file}`);
  if (!isCurrent(outputPath, css)) stale.push("theme.css");
  return stale;
}

if (process.argv.includes("--check")) {
  const stale = staleOutputs();
  if (stale.length > 0) {
    console.error(`Out of date: ${stale.join(", ")}. Run \`npm run build\`.`);
    process.exit(1);
  }
  console.log(`theme.css and ${snippets.size} snippets are current (${modules.length} modules, ${EMBEDDED_FACES.length} faces).`);
} else {
  writeFileSync(outputPath, css);
  rmSync(snippetDir, { recursive: true, force: true });
  mkdirSync(snippetDir);
  for (const [file, text] of snippets) writeFileSync(join(snippetDir, file), text);
  console.log(`Built theme.css from ${modules.length} modules and ${EMBEDDED_FACES.length} faces, and ${snippets.size} snippets.`);
}
